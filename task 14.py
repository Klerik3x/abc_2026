#todo: Дан массив размера N. Найти минимальное растояние между одинаковыми значениями в массиве и вывести их индексы.
# Одинаковых значение может быть два и более !
# Пример:
# mass = [1,2,17,54,30,89,2,1,6,2]
# Для числа 1 минимальное растояние в массиве по индексам: 0 и 7
# Для числа 2 минимальное растояние в массиве по индексам: 6 и 9
# Для числа 17 нет минимального растояния т.к элемент в массиве один.


# Исходный массив
mass = [1, 2, 17, 54, 30, 89, 2, 1, 6, 2]

# ШАГ 1: пустой словарь
positions = {}


# ШАГ 2: собираем индексы
for i, x in enumerate(mass):
    if x not in positions:        # если числа ещё нет
        positions[x] = []         # создаём для него пустой список
    positions[x].append(i)        # добавляем текущий индекс в список


# ШАГ 3: обрабатываем числа
for number, indexes in positions.items():
    if len(indexes) < 2:
        print(f"Для числа {number} нет минимального расстояния т.к элемент в массиве один.")
    else:
        # 1. Временный минимум — первая пара
        min_dist = indexes[1] - indexes[0]
        best_i = indexes[0]
        best_j = indexes[1]

        # 2. Перебираем остальные соседние пары
        for k in range(1, len(indexes)):
            dist = indexes[k] - indexes[k - 1]
            if dist < min_dist:
                min_dist = dist
                best_i = indexes[k - 1]
                best_j = indexes[k]

        # 3. Выводим результат
        print(f"Для числа {number} минимальное расстояние по индексам: {best_i} и {best_j}")
